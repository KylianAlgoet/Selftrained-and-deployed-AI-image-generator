"""Seeded generator for the minimal-geometric style (project-original assets).

Every image is fully determined by its seed: identical seed -> identical
bytes, so provenance is `generator@version + seed` and licensing is
project-original by construction (DR-006). Images use a deck-like tall
aspect ratio.
"""

import random
from dataclasses import asdict, dataclass
from pathlib import Path

from PIL import Image, ImageDraw

GENERATOR_VERSION = "1.0"
CANVAS_SIZE = (512, 1536)

# Curated flat palettes (background, then accent colors).
PALETTES = [
    ["#f4f1ea", "#e63946", "#1d3557", "#f1a208"],
    ["#101828", "#ff5722", "#00bcd4", "#ffc107"],
    ["#f7f3e9", "#2a9d8f", "#264653", "#e76f51"],
    ["#1b1b1e", "#8e24aa", "#03dac6", "#ffd166"],
    ["#eae4d9", "#0f4c5c", "#e36414", "#5f0f40"],
    ["#f5f5f5", "#111111", "#d62828", "#003049"],
]

SHAPE_KINDS = ["circle", "ring", "triangle", "bar", "diamond", "arc"]


@dataclass(frozen=True)
class GeneratorConfig:
    seed: int
    palette_index: int
    shape_count: int
    version: str = GENERATOR_VERSION


def _draw_shape(draw: ImageDraw.ImageDraw, rng: random.Random, kind: str, color: str, w: int, h: int) -> None:
    cx = rng.randint(int(w * 0.2), int(w * 0.8))
    cy = rng.randint(int(h * 0.08), int(h * 0.92))
    size = rng.randint(int(w * 0.15), int(w * 0.45))
    if kind == "circle":
        draw.ellipse([cx - size, cy - size, cx + size, cy + size], fill=color)
    elif kind == "ring":
        width = max(6, size // 4)
        draw.ellipse([cx - size, cy - size, cx + size, cy + size], outline=color, width=width)
    elif kind == "triangle":
        flip = rng.choice([-1, 1])
        draw.polygon([(cx, cy - flip * size), (cx - size, cy + flip * size), (cx + size, cy + flip * size)], fill=color)
    elif kind == "bar":
        thickness = rng.randint(int(w * 0.06), int(w * 0.14))
        skew = rng.randint(-size // 2, size // 2)
        draw.polygon(
            [(cx - size, cy - thickness // 2 + skew), (cx + size, cy - thickness // 2 - skew),
             (cx + size, cy + thickness // 2 - skew), (cx - size, cy + thickness // 2 + skew)],
            fill=color,
        )
    elif kind == "diamond":
        draw.polygon([(cx, cy - size), (cx + size // 2, cy), (cx, cy + size), (cx - size // 2, cy)], fill=color)
    elif kind == "arc":
        width = max(8, size // 3)
        start = rng.randint(0, 360)
        draw.arc([cx - size, cy - size, cx + size, cy + size], start, start + rng.randint(90, 270), fill=color, width=width)


def generate_geometric(seed: int, out_path: str | Path) -> GeneratorConfig:
    """Render one deterministic minimal-geometric decal image to out_path."""
    rng = random.Random(seed)
    palette_index = rng.randrange(len(PALETTES))
    palette = PALETTES[palette_index]
    shape_count = rng.randint(4, 9)

    img = Image.new("RGB", CANVAS_SIZE, palette[0])
    draw = ImageDraw.Draw(img)
    for _ in range(shape_count):
        kind = rng.choice(SHAPE_KINDS)
        color = rng.choice(palette[1:])
        _draw_shape(draw, rng, kind, color, *CANVAS_SIZE)

    out_path = Path(out_path)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    img.save(out_path, "PNG")
    return GeneratorConfig(seed=seed, palette_index=palette_index, shape_count=shape_count)


def config_note(config: GeneratorConfig) -> str:
    """Manifest note string recording full reproduction parameters."""
    parts = ", ".join(f"{k}={v}" for k, v in asdict(config).items())
    return f"generated by ml/dataset/generate_geometric.py ({parts})"
